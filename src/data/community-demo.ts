// Stable, varied activity times and small engagement counts for the authored sample conversations.
function activitySeed(value: number) {
  let seed = Math.imul(value ^ 0x9e3779b9, 0x85ebca6b)
  seed = Math.imul(seed ^ (seed >>> 13), 0xc2b2ae35)
  return (seed ^ (seed >>> 16)) >>> 0
}

function activityTime(dayOffset: number, minuteOfDay: number) {
  // Treat these UTC components as local calendar values, then explicitly label China time.
  return new Date(Date.UTC(2026, 2, 2 + dayOffset, 0, minuteOfDay))
    .toISOString().slice(0, 19) + '+08:00'
}

export const COMMUNITY_DEMO_POSTS: DemoPost[] = records.map((record, index) => {
  const [topic, title, content, tags, replies] = record
  const serial = String(index + 1).padStart(3, '0')
  // 118 days separate March 2 and June 28; deterministic dates keep the demo reproducible.
  const dayOffset = Math.round(index * 118 / 75)
  const seed = activitySeed(index + 1)
  const postedAt = 8 * 60 + seed % (14 * 60)
  let replyAt = postedAt
  const [author, role] = members[index % members.length]
  return {
    id: `demo-post-${serial}`,
    topic,
    title,
    content,
    author,
    role,
    createdAt: activityTime(dayOffset, postedAt),
    likes: ((seed >>> 8) % 13) + ((seed >>> 16) % 9) + (seed % 11 === 0 ? 8 : 0),
    tags,
    replies: replies.map((reply, replyIndex) => {
      replyAt += 9 + activitySeed((index + 1) * 17 + replyIndex) % 117
      return {
        id: `demo-reply-${serial}-${replyIndex + 1}`,
        author: members[(index + 3 + replyIndex * 6) % members.length][0],
        content: reply,
        createdAt: activityTime(dayOffset, replyAt),
      }
    }),
  }
}).reverse()
